  // Проситись у "persistent storage" — браузер сам вирішує, чи задовольнити прохання
  // (типово задовольняє, якщо сайт доданий на головний екран або відвідується часто), але
  // якщо задовольнить — браузер НЕ матиме права тихо почистити IndexedDB цього сайту під
  // тиском нестачі місця (на відміну від "best-effort" сховища за замовчуванням, яке можна
  // прибрати без попередження). Це не дає доступу до файлової системи телефону напряму —
  // такого в звичайній вебсторінці просто не існує (пісочниця браузера, навмисне обмеження
  // безпеки, однакове для всіх сайтів) — але суттєво знижує ризик втрати даних конкретно
  // цього сайту. Best-effort: якщо API немає чи браузер відмовив — просто тихо ігноруємо.
  if(navigator.storage && navigator.storage.persist){
    navigator.storage.persist().catch(function(){});
  }
